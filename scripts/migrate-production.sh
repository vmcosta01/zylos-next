#!/usr/bin/env bash
# Zylos-Next Production Migration Script
# Migrates from Hermes v1 to Zylos-Next with zero downtime strategy
#
# Usage: ./migrate-production.sh [--dry-run] [--skip-backup]
# Requires: hermes CLI, sqlite3, docker (optional)

set -euo pipefail

DRY_RUN="${1:-}"
SKIP_BACKUP="${2:-}"
TIMESTAMP=$(date +%Y%m%d_%H%M%S)
MIGRATION_DIR="./migration_${TIMESTAMP}"
LOG_FILE="${MIGRATION_DIR}/migration.log"

log() {
    local msg="[$(date '+%Y-%m-%d %H:%M:%S')] $*"
    echo "$msg" | tee -a "$LOG_FILE"
}

check_prerequisites() {
    log "Checking prerequisites..."
    
    local missing=()
    command -v hermes >/dev/null 2>&1 || missing+=("hermes")
    command -v sqlite3 >/dev/null 2>&1 || missing+=("sqlite3")
    command -v cargo >/dev/null 2>&1 || missing+=("cargo")
    
    if [[ ${#missing[@]} -gt 0 ]]; then
        log "ERROR: Missing required tools: ${missing[*]}"
        exit 1
    fi
    
    # Verify zylos-gateway binary exists
    if [[ ! -f "./target/release/zylos-gateway" ]]; then
        log "Building zylos-gateway release binary..."
        cargo build --release -p zylos-gateway
    fi
    
    log "All prerequisites satisfied."
}

create_backup() {
    if [[ "$SKIP_BACKUP" == "--skip-backup" ]]; then
        log "Skipping backup (--skip-backup flag)"
        return
    fi
    
    log "Creating backup in ${MIGRATION_DIR}/backup/"
    mkdir -p "${MIGRATION_DIR}/backup"
    
    # Export Hermes state
    if [[ "$DRY_RUN" != "--dry-run" ]]; then
        hermes export --format json --output "${MIGRATION_DIR}/backup/hermes-export.json" 2>&1 | tee -a "$LOG_FILE" || {
            log "WARNING: hermes export failed, continuing with available data"
        }
        
        hermes skills export --dir "${MIGRATION_DIR}/backup/skills/" 2>&1 | tee -a "$LOG_FILE" || {
            log "WARNING: hermes skills export failed"
        }
        
        hermes memory snapshot --output "${MIGRATION_DIR}/backup/hermes-memory.db" 2>&1 | tee -a "$LOG_FILE" || {
            log "WARNING: hermes memory snapshot failed"
        }
    else
        log "[DRY-RUN] Would export hermes state to ${MIGRATION_DIR}/backup/"
    fi
    
    log "Backup complete."
}

migrate_memory() {
    log "Migrating memory database..."
    
    local src_db="${MIGRATION_DIR}/backup/hermes-memory.db"
    local dest_db="./data/zylos-memory.db"
    
    if [[ ! -f "$src_db" ]]; then
        log "WARNING: Source memory database not found at ${src_db}"
        log "Starting with empty memory database"
        mkdir -p ./data
        sqlite3 "$dest_db" "CREATE TABLE IF NOT EXISTS memory (id INTEGER PRIMARY KEY, key TEXT, value TEXT, created_at TEXT);"
        return
    fi
    
    mkdir -p ./data
    
    if [[ "$DRY_RUN" != "--dry-run" ]]; then
        # Copy and let consolidation handle format differences
        cp "$src_db" "$dest_db"
        log "Memory database copied. Consolidation will run on first startup."
    else
        log "[DRY-RUN] Would copy ${src_db} -> ${dest_db}"
    fi
}

migrate_skills() {
    log "Migrating skills registry..."
    
    local src_dir="${MIGRATION_DIR}/backup/skills/"
    local dest_dir="./skills/"
    
    if [[ ! -d "$src_dir" ]]; then
        log "WARNING: Source skills directory not found at ${src_dir}"
        return
    fi
    
    mkdir -p "$dest_dir"
    
    if [[ "$DRY_RUN" != "--dry-run" ]]; then
        cp -r "$src_dir"/* "$dest_dir"/ 2>/dev/null || true
        local count=$(find "$dest_dir" -name "SKILL.md" | wc -l)
        log "Migrated ${count} skills to ${dest_dir}"
    else
        local count=$(find "$src_dir" -name "SKILL.md" 2>/dev/null | wc -l)
        log "[DRY-RUN] Would migrate ${count} skills from ${src_dir} -> ${dest_dir}"
    fi
}

generate_config() {
    log "Generating production configuration..."
    
    cat > ./config.production.toml << 'TOML'
# Zylos-Next Production Configuration
# Generated by migrate-production.sh

[server]
listen_addr = "0.0.0.0:3000"
shutdown_timeout_secs = 10
max_connections = 2048

[health]
ready_enabled = true
live_enabled = true

[soar]
audit_key = "CHANGE-ME-generate-with-openssl-rand-hex-32"
event_bus_capacity = 512

[skills]
index_path = "./skills"
TOML

    log "Production config written to ./config.production.toml"
    log "IMPORTANT: Change soar.audit_key before deploying!"
}

setup_monitoring() {
    log "Setting up monitoring configuration..."
    
    mkdir -p ./monitoring/{prometheus,grafana,alertmanager}
    
    # Prometheus config
    cat > ./monitoring/prometheus/prometheus.yml << 'YAML'
global:
  scrape_interval: 15s
  evaluation_interval: 15s

scrape_configs:
  - job_name: 'zylos-gateway'
    static_configs:
      - targets: ['localhost:3000']
    metrics_path: '/gateway/metrics'
    scrape_interval: 5s

  - job_name: 'zylos-health'
    static_configs:
      - targets: ['localhost:3000']
    metrics_path: '/gateway/health'
    scrape_interval: 10s
YAML

    # Alertmanager config
    cat > ./monitoring/alertmanager/alertmanager.yml << 'YAML'
global:
  resolve_timeout: 5m

route:
  group_by: ['alertname', 'severity']
  group_wait: 30s
  group_interval: 5m
  repeat_interval: 4h
  receiver: 'telegram'

receivers:
  - name: 'telegram'
    webhook_configs:
      - url: 'http://localhost:9095/alert'
        send_resolved: true

inhibit_rules:
  - source_match:
      severity: 'critical'
    target_match:
      severity: 'warning'
    equal: ['alertname']
YAML

    # Grafana dashboard provisioning
    cat > ./monitoring/grafana/provisioning.yml << 'YAML'
apiVersion: 1

providers:
  - name: 'Zylos-Next'
    orgId: 1
    folder: ''
    type: file
    disableDeletion: false
    editable: true
    options:
      path: /var/lib/grafana/dashboards
YAML

    log "Monitoring configs written to ./monitoring/"
}

setup_backups() {
    log "Setting up automated backup script..."
    
    cat > ./scripts/backup-daily.sh << 'BASH'
#!/usr/bin/env bash
# Daily backup for Zylos-Next production data
set -euo pipefail

BACKUP_DIR="/var/backups/zylos-next"
TIMESTAMP=$(date +%Y%m%d)
RETENTION_DAYS=30

mkdir -p "$BACKUP_DIR"

# Backup SQLite databases
for db in ./data/*.db; do
    if [[ -f "$db" ]]; then
        sqlite3 "$db" ".backup '${BACKUP_DIR}/$(basename "$db" .db)_${TIMESTAMP}.db'"
    fi
done

# Backup skills
tar czf "${BACKUP_DIR}/skills_${TIMESTAMP}.tar.gz" ./skills/

# Backup config
cp ./config.production.toml "${BACKUP_DIR}/config_${TIMESTAMP}.toml"

# Prune old backups
find "$BACKUP_DIR" -name "*_*.db" -mtime +${RETENTION_DAYS} -delete
find "$BACKUP_DIR" -name "skills_*.tar.gz" -mtime +${RETENTION_DAYS} -delete
find "$BACKUP_DIR" -name "config_*.toml" -mtime +${RETENTION_DAYS} -delete

echo "[$(date)] Backup complete: ${BACKUP_DIR}"
BASH

    chmod +x ./scripts/backup-daily.sh
    log "Backup script created at ./scripts/backup-daily.sh"
    log "Add to crontab: 0 2 * * * /path/to/scripts/backup-daily.sh"
}

validate_migration() {
    log "Validating migration..."
    
    if [[ "$DRY_RUN" == "--dry-run" ]]; then
        log "[DRY-RUN] Skipping validation"
        return
    fi
    
    # Check gateway starts
    log "Starting gateway for validation (10s timeout)..."
    timeout 10 ./target/release/zylos-gateway --config ./config.production.toml &
    GW_PID=$!
    sleep 3
    
    # Health check
    if curl -sf http://localhost:3000/gateway/health > /dev/null 2>&1; then
        log "✅ Health check passed"
    else
        log "❌ Health check failed"
    fi
    
    # Ready check
    if curl -sf http://localhost:3000/gateway/ready > /dev/null 2>&1; then
        log "✅ Readiness check passed"
    else
        log "❌ Readiness check failed"
    fi
    
    # Kill gateway
    kill $GW_PID 2>/dev/null || true
    wait $GW_PID 2>/dev/null || true
    
    log "Validation complete."
}

print_summary() {
    log "=========================================="
    log "  MIGRATION SUMMARY"
    log "=========================================="
    log "Migration dir: ${MIGRATION_DIR}"
    log "Log file: ${LOG_FILE}"
    log ""
    log "Next steps:"
    log "  1. Review config.production.toml (change audit_key!)"
    log "  2. Set up monitoring: docker-compose -f monitoring/docker-compose.yml up -d"
    log "  3. Configure crontab for daily backups"
    log "  4. Start gateway: ./target/release/zylos-gateway --config config.production.toml"
    log "  5. Monitor for 1 week (zero P0/P1 incidents required)"
    log ""
    log "Rollback: restore from ${MIGRATION_DIR}/backup/ if issues arise"
    log "=========================================="
}

main() {
    mkdir -p "$MIGRATION_DIR"
    touch "$LOG_FILE"
    
    log "Starting Zylos-Next production migration"
    log "Mode: ${DRY_RUN:-live}"
    
    check_prerequisites
    create_backup
    migrate_memory
    migrate_skills
    generate_config
    setup_monitoring
    setup_backups
    validate_migration
    print_summary
    
    log "Migration complete."
}

main "$@"